# Operators are special symbols in Python that perform an action on values.
# The values an operator works on are called operands.
# This file covers two groups of operators:
# 1. Arithmetic operators - used to do maths (+, -, *, /, %)
# 2. Comparison operators - used to compare two values (>, <, ==, !=)
# Arithmetic operators give back a number as the result.
# Comparison operators always give back a boolean value: True or False.

num1=13

num2=3

# Step 1: The + operator adds num1 and num2 together, then prints the total.
print(num1+num2)

# Step 2: The - operator subtracts num2 from num1, then prints the difference.
print(num1-num2)

# Step 3: The * operator multiplies num1 and num2, then prints the product.
print(num1*num2)

# Step 4: The / operator divides num1 by num2. Division in Python always returns a decimal (float) value, even if the numbers divide evenly.
print(num1/num2)

# Step 5: The % operator is called modulus. It divides num1 by num2 and gives back only the remainder, not the full answer.
print(num1%num2)

# Step 6: The > operator checks if num1 is greater than num2. Since 13 is greater than 3, this prints True.
print(num1>num2)

# Step 7: The < operator checks if num1 is less than num2. Since 13 is not less than 3, this prints False.
print(num1<num2)

# Step 8: The == operator checks if num1 and num2 are equal in value. Two equal signs are used for comparing, while a single equal sign (=) is used for assigning a value to a variable. Since 13 is not equal to 3, this prints False.
print(num1==num2)

# Step 9: The != operator checks if num1 and num2 are NOT equal. Since 13 is different from 3, this prints True.
print(num1!=num2)
